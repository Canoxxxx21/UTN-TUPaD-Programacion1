# DESAFÍO 2: La Universalidad de la Compuerta NAND
# =====================================================================
def nand_gate(a, b):
    """NAND(A, B) = (A · B)', definición de la compuerta NAND."""
    return not (a and b)


def or_con_nands(a, b):
    """
    Construcción de una compuerta OR utilizando ÚNICAMENTE compuertas NAND.

    Justificación:
      1. NAND(A, A) = (A · A)' = A', por idempotencia y complemento.
      2. NAND(A', B') = (A' · B')' = A + B, por De Morgan.
    """
    # Conectar las dos entradas de cada NAND produce sus complementos.
    not_a = nand_gate(a, a)
    not_b = nand_gate(b, b)

    # De Morgan convierte la NAND de los complementos en una OR.
    return nand_gate(not_a, not_b)


def desafio_2():
    print("=" * 60)
    print("RESPUESTA 2 - DESAFÍO 2: OR construida exclusivamente con NANDs")
    print("=" * 60)

    print(f"\n{'A':>6} {'B':>6} {'OR nativo':>10} {'OR c/NANDs':>11} {'¿Igual?':>8}")
    print("-" * 46)

    # La enumeración exhaustiva valida la identidad obtenida por idempotencia
    # y De Morgan; la comparación no realiza una nueva simplificación.
    todas_iguales = True
    for a, b in product([False, True], repeat=2):
        nativo = a or b
        construido = or_con_nands(a, b)
        comparacion = nativo == construido
        todas_iguales = todas_iguales and comparacion
        print(f"{a!s:>6} {b!s:>6} {nativo!s:>10} {construido!s:>11} {comparacion!s:>8}")
    print("\nRespuesta:")
    print(f"  La construcción NAND equivale a OR en todos los casos: {todas_iguales}.")
    print("  Expresión: A + B = (A NAND A) NAND (B NAND B).")
    print("  Justificación: doble negación por NAND(A,A) = A' y ley de De Morgan.\n")


