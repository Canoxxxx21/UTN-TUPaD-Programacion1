# DESAFÍO 3: El "Kill Switch" y la Verificación de Minimización
# =====================================================================
def f_original(ingresos, antiguedad, vip, deuda):
    # F = ((I · A) + V) · D'. El factor D' bloquea cualquier aprobación
    # cuando existe deuda, por la Ley del Elemento Nulo.
    return ((ingresos and antiguedad) or vip) and not deuda


def f_minima(ingresos, antiguedad, vip, deuda):
    # Expresión alternativa provista para evaluar; no se presupone equivalente
    # a la original. Se compara con todos los casos de prueba disponibles.
    return ingresos and not deuda


def desafio_3():
    print("=" * 60)
    print("RESPUESTA 3 - DESAFÍO 3: Kill Switch y Verificación de Minimización")
    print("=" * 60)

    # Las entradas incluyen casos con deuda (D = 1) para comprobar el Kill
    # Switch: por Elemento Nulo, cualquier término AND D' vale 0 si D' = 0.
    # Casos de prueba orientativos para analizar discrepancias
    # (falsos positivos/falsos negativos).
    casos = [
        (True,  True,  False, False),
        (True,  False, False, False),
        (False, True,  True,  False),
        (False, False, True,  False),
        (True,  True,  True,  False),
        (True,  True,  False, True),
        (False, False, True,  True),
        (True,  False, True,  True),
        (False, True,  False, False),
        (False, False, False, False),
    ]

    # Las comprensiones calculan ambas funciones sobre las mismas entradas.
    # La igualdad de listas comprueba equivalencia en estos casos; no es una
    # ley de simplificación, sino una verificación por tabla de verdad.
    resultados_originales = [
        f_original(ingresos, antiguedad, vip, deuda)
        for ingresos, antiguedad, vip, deuda in casos
    ]
    resultados_minimos = [
        f_minima(ingresos, antiguedad, vip, deuda)
        for ingresos, antiguedad, vip, deuda in casos
    ]

    print(f"\n{'Caso':>4} {'Ing.':>6} {'Antig.':>7} {'VIP':>6} {'Deuda':>7} "
          f"{'Original':>10} {'Mínima':>8} {'Coinciden':>10}")
    print("-" * 70)
    for numero, (caso, original, minima) in enumerate(
        zip(casos, resultados_originales, resultados_minimos), start=1
    ):
        ingresos, antiguedad, vip, deuda = caso
        print(f"{numero:>4} {ingresos!s:>6} {antiguedad!s:>7} {vip!s:>6} "
              f"{deuda!s:>7} {original!s:>10} {minima!s:>8} "
              f"{(original == minima)!s:>10}")

    coinciden = resultados_originales == resultados_minimos
    # Se clasifican los contraejemplos a la equivalencia: Elemento Nulo
    # explica el bloqueo por deuda, pero no elimina I, A ni V cuando D = 0.
    falsos_positivos = [
        numero for numero, (original, minima) in enumerate(
            zip(resultados_originales, resultados_minimos), start=1
        )
        if minima and not original
    ]
    falsos_negativos = [
        numero for numero, (original, minima) in enumerate(
            zip(resultados_originales, resultados_minimos), start=1
        )
        if original and not minima
    ]

    print("\nRespuesta:")
    print(f"  Resultados de la función original: {resultados_originales}")
    print(f"  Resultados de la función mínima:  {resultados_minimos}")
    print(f"  ¿Las listas son iguales?: {coinciden}")
    print(f"  Falsos positivos de la función mínima (casos): {falsos_positivos}")
    print(f"  Falsos negativos de la función mínima (casos): {falsos_negativos}")
    print("\nJustificación:")
    print("  La función original es F = ((I · A) + V) · D', mientras que la propuesta "
          "alternativa es Fmín = I · D'.")
    print("  No son equivalentes: la propuesta elimina los criterios de antigüedad y VIP. "
          "En estos casos produce un falso positivo en el caso 2 y falsos negativos "
          "en los casos 3 y 4.")
    print("  El control de deuda funciona como Kill Switch en ambas expresiones: si D = 1, "
          "entonces D' = 0 y toda la salida vale 0 por la Ley del Elemento Nulo "
          "(X · 0 = 0). La discrepancia cuando no hay deuda demuestra que esta ley "
          "justifica el bloqueo, pero no hace equivalentes las dos funciones.\n")


