# DESAFÍO 1: Generador Automático de Formas Canónicas (SOP)
# =====================================================================
def desafio_1():
    print("=" * 60)
    print("RESPUESTA 1 - DESAFÍO 1: Tabla de verdad y forma canónica SOP")
    print("=" * 60)

    # Se utiliza la función de ejemplo incluida en el material:
    # F = (A + B) · C'. En Python, or representa +, and representa · y
    # not representa el complemento.
    def salida(a, b, c):
        return (a or b) and not c

    # La enumeración de la tabla no transforma la expresión: evalúa las ocho
    # combinaciones para identificar las filas verdaderas de la función.
    # product entrega las filas en orden binario, con A como bit más
    # significativo y C como el menos significativo; por eso el índice
    # coincide con el número del mintermino.
    tabla = list(product([False, True], repeat=3))
    minterminos = []

    print(f"\n{'m':>3} {'A':>6} {'B':>6} {'C':>6} {'Salida':>8}")
    print("-" * 34)

    for indice, (a, b, c) in enumerate(tabla):
        resultado = salida(a, b, c)
        print(f"m{indice:<2} {a!s:>6} {b!s:>6} {c!s:>6} {resultado!s:>8}")

        # La condición selecciona los minterminos donde F = 1; no aplica
        # una simplificación, sino la definición de forma canónica SOP.
        if resultado:
            minterminos.append(indice)

    # Para cada fila verdadera se forma un mintermino: una variable aparece
    # directa si vale 1 y complementada si vale 0. La suma de esos productos
    # es, por definición, la forma canónica SOP.
    literales = []
    for indice in minterminos:
        a, b, c = tabla[indice]
        # En cada producto, la variable directa representa el valor 1 y la
        # complementada representa el valor 0; así el término identifica
        # exactamente esa fila de la tabla.
        termino = "".join(
            variable if valor else f"{variable}'"
            for variable, valor in zip(("A", "B", "C"), (a, b, c))
        )
        literales.append(termino)

    print("\nRespuesta:")
    print(f"  Minterminos: {', '.join(f'm{indice}' for indice in minterminos)}")
    print(f"  Forma canónica SOP: F = {' + '.join(literales)}")
    print(f"  Notacion abreviada: F(A, B, C) = sum m({', '.join(map(str, minterminos))})")
    # Simplificación de la SOP:
    # A'BC' + AB'C' + ABC' = C'[B(A' + A) + A(B' + B)]
    # = C'(A + B), usando distributiva y complemento (X' + X = 1),
    # y luego identidad (X · 1 = X).
    print("  Simplificación: F = C'(A + B)")
    print("  Justificación: leyes distributiva, complemento e identidad.\n")


